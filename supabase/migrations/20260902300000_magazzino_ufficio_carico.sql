-- 1 · gli articoli, creati o rinfrescati
insert into mag_articoli (codice, barcode, descrizione, gruppo, sottogruppo, marca,
                          iva_acquisto, iva_vendita, costo_ultimo, prezzo, reparto, fonte, attivo)
select a.codice, a.barcode, a.descrizione, a.gruppo, a.sottogruppo, a.marca,
       a.iva_a, a.iva_v, a.costo, a.prezzo, a.reparto, 'magazzino-ufficio', true
from _art a
on conflict (codice) do update set
    barcode      = coalesce(excluded.barcode, mag_articoli.barcode),
    descrizione  = coalesce(nullif(excluded.descrizione,''), mag_articoli.descrizione),
    costo_ultimo = coalesce(excluded.costo_ultimo, mag_articoli.costo_ultimo),
    prezzo       = coalesce(excluded.prezzo, mag_articoli.prezzo);

-- 2 · le disponibilità dell'ufficio
insert into mag_giacenze (codice, negozio, azienda, quantita, contata_il, contata_da)
select g.codice, 'Ufficio', 'T1', g.quantita, now(), 'carico iniziale da file gestionale'
from _gia g
on conflict (codice, negozio, azienda) do update set
    quantita = excluded.quantita, contata_il = now(), contata_da = excluded.contata_da;

-- 3 · i pezzi con numero di serie
-- ⚠️ NON si tocca un seriale già vivo altrove: se un telefono risulta già in un
-- negozio, il file dell'ufficio è più vecchio della realtà, e vince la realtà.
insert into mag_unita (seriale, tipo_seriale, codice, descrizione, azienda, negozio,
                       stato, valore, prezzo_vendita, caricato_il, caricato_da)
select u.seriale, 'imei', u.codice, u.descrizione, 'T1', 'Ufficio',
       'disponibile', u.costo, u.prezzo, now(), 'carico iniziale da file gestionale'
from _uni u
where not exists (select 1 from mag_unita m where m.seriale = u.seriale and m.stato not in ('venduto','annullato'))
  and not exists (select 1 from usati x where x.imei = u.seriale);

do $$
declare a int; g int; p int; u int;
begin
    select count(*), coalesce(sum(quantita),0) into g, p from mag_giacenze where negozio='Ufficio';
    select count(*) into u from mag_unita where negozio='Ufficio' and stato='disponibile';
    select count(*) into a from mag_articoli where fonte='magazzino-ufficio';
    raise notice 'Ufficio: % righe di giacenza, % pezzi, % unita con IMEI, % articoli marcati ufficio', g, p, u, a;
    if g = 0 then raise exception 'non e entrata nessuna giacenza'; end if;
end $$;
